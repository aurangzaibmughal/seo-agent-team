class CodeTemplateEngine:
    """Renders all SEO code artifacts using Jinja2 templates."""

    @classmethod
    def render_nextjs_root_layout(
        cls,
        base_url: str,
        default_title: str,
        default_description: str,
        brand_name: str,
        is_demo: bool = False
    ) -> str:
        header = get_comment_header("ts", is_demo)
        clean_brand = brand_name.strip()
        clean_title = (default_title or f"{clean_brand} | Pakistan's Trusted Digital & Web Agency").strip()
        if len(clean_title) > 60:
            parts = [p.strip() for p in re.split(r"[|—–]", clean_title) if p.strip()]
            candidate = None
            if len(parts) >= 2:
                opt1 = f"{clean_brand} | {parts[-1]}"
                if len(opt1) <= 60:
                    candidate = opt1
                else:
                    for seg in parts:
                        if seg.lower() != clean_brand.lower():
                            opt2 = f"{clean_brand} | {seg}"
                            if len(opt2) <= 60:
                                candidate = opt2
                                break
            if candidate:
                clean_title = candidate
            else:
                clean_title = truncate_at_word_boundary(clean_title, 60)

        # Enforce description <= 155 characters
        clean_desc = (default_description or "").strip()
        if len(clean_desc) > 155:
            clean_desc = truncate_at_word_boundary(clean_desc, 155)

        t = Template(TPL_NEXTJS_ROOT_LAYOUT)
        return t.render(
            header=header,
            base_url=base_url.rstrip("/"),
            default_title_literal=escape_ts_literal(clean_title),
            default_description_literal=escape_ts_literal(clean_desc),
            brand_name=clean_brand,
            brand_name_literal=escape_ts_literal(clean_brand)
        )

    @classmethod
    def render_nextjs_page_metadata(
        cls,
        title: str,
        description: str,
        canonical_url: str,
        target_file: str = "app/page.tsx",
        og_type: str = "website",
        is_demo: bool = False
    ) -> str:
        header = get_comment_header("ts", is_demo)
        clean_title = (title or "").strip()
        if len(clean_title) > 60:
            clean_title = truncate_at_word_boundary(clean_title, 60)
        clean_desc = (description or "").strip()
        if len(clean_desc) > 155:
            clean_desc = truncate_at_word_boundary(clean_desc, 155)

        t = Template(TPL_NEXTJS_PAGE_METADATA)
        return t.render(
            header=header,
            target_file=target_file,
            title_literal=escape_ts_literal(clean_title),
            description_literal=escape_ts_literal(clean_desc),
            canonical_url=canonical_url,
            og_type=og_type
        )

