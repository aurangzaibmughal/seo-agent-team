def escape_ts_literal(s: Optional[str]) -> str:
    """Escapes quotes and backslashes for a TypeScript string literal without unicode escaping."""
    if not s:
        return "''"
    clean = re.sub(r"\s+", " ", str(s)).strip()
    escaped = clean.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"

def truncate_at_word_boundary(text: str, max_chars: int = 140) -> str:
    """Truncates text at whitespace word boundary without cutting words in half."""
    if not text:
        return ""
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= max_chars:
        return text
    cut = text[:max_chars]
    last_space = cut.rfind(" ")
    if last_space > int(max_chars * 0.5):
        cut = cut[:last_space]
    return cut.rstrip(".,;:- ") + "..."

def get_comment_header(comment_type: str, is_demo: bool = False) -> str:
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    demo_badge = "\n// *** DEMO DATA — SYNTHETIC BENCHMARK FIXTURE — REVIEW REQUIRED ***" if is_demo else ""
    demo_badge_hash = "\n# *** DEMO DATA — SYNTHETIC BENCHMARK FIXTURE — REVIEW REQUIRED ***" if is_demo else ""
    demo_badge_xml = "\n<!-- *** DEMO DATA — SYNTHETIC BENCHMARK FIXTURE — REVIEW REQUIRED *** -->" if is_demo else ""

    if comment_type in ("slash", "ts", "js", "php"):
        return (
            f"// Generated by SEO Agent Team Code Generator on {now_str}\n"
            f"// Status: needs human review\n"
            f"// WARNING: Test thoroughly in a staging environment before deploying.{demo_badge}\n"
        )
    elif comment_type in ("hash", "htaccess", "robots"):
        return (
            f"# Generated by SEO Agent Team Code Generator on {now_str}\n"
            f"# Status: needs human review\n"
            f"# WARNING: Test thoroughly in a staging environment before deploying.{demo_badge_hash}\n"
        )
    elif comment_type == "llms":
        # llms.txt standard strictly requires # H1 as the very first line - no header comments
        return ""
    elif comment_type in ("xml", "html"):
        return (
            f"<!-- Generated by SEO Agent Team Code Generator on {now_str} -->\n"
            f"<!-- Status: needs human review -->\n"
            f"<!-- WARNING: Test thoroughly in a staging environment before deploying. -->{demo_badge_xml}\n"
        )
    return ""

