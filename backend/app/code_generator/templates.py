class CodeTemplateEngine:
    """Renders all SEO code artifacts using Jinja2 templates."""

    @classmethod
    def render_nextjs_root_layout(cls, base_url: str, default_title: str, default_description: str, brand_name: str, is_demo: bool = False) -> str:
        header = get_comment_header("ts", is_demo)
        t = Template(TPL_NEXTJS_ROOT_LAYOUT)
        return t.render(
            header=header,
            base_url=base_url.rstrip("/"),
            default_title=default_title,
            default_description=default_description,
            brand_name=brand_name
        )

    @classmethod
    def render_nextjs_page_metadata(cls, title: str, description: str, canonical_url: str, h1_text: str = "", is_demo: bool = False) -> str:
        header = get_comment_header("ts", is_demo)
        t = Template(TPL_NEXTJS_PAGE_METADATA)
        return t.render(
            header=header,
            title=title,
            description=description,
            canonical_url=canonical_url,
            h1_text=h1_text or title
        )

    @classmethod
    def render_nextjs_sitemap_ts(cls, sitemap_items: List[Dict[str, Any]], is_demo: bool = False) -> str:
        header = get_comment_header("ts", is_demo)
        t = Template(TPL_NEXTJS_SITEMAP_TS)
        return t.render(header=header, sitemap_items=sitemap_items)

    @classmethod
    def render_nextjs_robots_ts(cls, sitemap_url: str, disallow_paths: List[str] = None, is_demo: bool = False) -> str:
        header = get_comment_header("ts", is_demo)
        t = Template(TPL_NEXTJS_ROBOTS_TS)
        return t.render(header=header, sitemap_url=sitemap_url, disallow_paths=disallow_paths or [])

    @classmethod
    def render_nextjs_jsonld_component(cls, example_schema: Dict[str, Any] = None, is_demo: bool = False) -> str:
        header = get_comment_header("ts", is_demo)
        t = Template(TPL_NEXTJS_JSONLD_COMPONENT)
        return t.render(header=header, schema_json=json.dumps(example_schema or {}, indent=2))

    @classmethod
    def render_nextjs_redirects(cls, redirects: List[Dict[str, str]], is_demo: bool = False) -> str:
        header = get_comment_header("js", is_demo)
        t = Template(TPL_NEXTJS_REDIRECTS)
        return t.render(header=header, redirects=redirects)

    @classmethod
    def render_sitemap_xml(cls, sitemap_items: List[Dict[str, Any]], is_demo: bool = False) -> str:
        header = get_comment_header("xml", is_demo)
        t = Template(TPL_SITEMAP_XML)
        return t.render(header=header, sitemap_items=sitemap_items)

    @classmethod
    def render_robots_txt(cls, sitemap_url: str, disallow_paths: List[str] = None, is_demo: bool = False) -> str:
        header = get_comment_header("robots", is_demo)
        t = Template(TPL_ROBOTS_TXT)
        return t.render(header=header, sitemap_url=sitemap_url, disallow_paths=disallow_paths or [])

    @classmethod
    def render_llms_txt(cls, site_name: str, site_summary: str, base_url: str, curated_links: List[Dict[str, str]], is_demo: bool = False) -> str:
        header = get_comment_header("llms", is_demo)
        t = Template(TPL_LLMS_TXT)
        return t.render(
            header=header,
            site_name=site_name,
            site_summary=site_summary,
            base_url=base_url.rstrip("/"),
            curated_links=curated_links
        )

    @classmethod
    def render_metadata_csv(cls, rewrites: List[Dict[str, Any]], is_demo: bool = False) -> str:
        """Renders metadata_table.csv containing verified on-page rewrites."""
        output = io.StringIO()
        if is_demo:
            output.write("# DEMO DATA — SYNTHETIC BENCHMARK FIXTURE — REVIEW REQUIRED\n")
        writer = csv.writer(output)
        writer.writerow(["url", "current_title", "suggested_title", "current_meta", "suggested_meta", "issue_ids", "status"])
        for r in rewrites:
            # Exclude no-op rows
            s_t = r.get("suggested_title")
            s_m = r.get("suggested_meta")
            if s_t == "no change needed" and s_m == "no change needed":
                continue
            writer.writerow([
                r.get("url", ""),
                r.get("current_title") or "",
                s_t or "",
                r.get("current_meta") or "",
                s_m or "",
                ";".join(r.get("issue_ids") or []),
                "needs human review"
            ])
        return output.getvalue()

    @classmethod
    def render_wordpress_functions_php(cls, schema_dict: Dict[str, Any], is_demo: bool = False) -> str:
        header = get_comment_header("php", is_demo)
        t = Template(TPL_WORDPRESS_FUNCTIONS_PHP)
        return t.render(header=header, schema_json_raw=json.dumps(schema_dict, indent=4))

    @classmethod
    def render_wordpress_htaccess(cls, redirects: List[Dict[str, str]], is_demo: bool = False) -> str:
        header = get_comment_header("htaccess", is_demo)
        t = Template(TPL_WORDPRESS_HTACCESS)
        return t.render(header=header, redirects=redirects)

    @classmethod
    def render_plain_html_head_snippet(cls, page_path: str, title: str, description: str, canonical_url: str, is_demo: bool = False) -> str:
        header = get_comment_header("html", is_demo)
        t = Template(TPL_PLAIN_HTML_HEAD_SNIPPET)
        return t.render(
            header=header,
            page_path=page_path,
            title=title,
            description=description,
            canonical_url=canonical_url
        )

    @classmethod
    def render_netlify_redirects(cls, redirects: List[Dict[str, str]], is_demo: bool = False) -> str:
        header = get_comment_header("hash", is_demo)
        t = Template(TPL_NETLIFY_REDIRECTS)
        return t.render(header=header, redirects=redirects)

    @classmethod
    def render_vercel_redirects(cls, redirects: List[Dict[str, str]], is_demo: bool = False) -> str:
        t = Template(TPL_VERCEL_JSON_REDIRECTS)
        return t.render(redirects=redirects)
